CREATE TABLE scan_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    reviewed_at timestamptz,
    schema_version integer NOT NULL DEFAULT 1,
    image_mime varchar(32) NOT NULL,
    image_filename varchar(255),
    image_sha256 char(64) NOT NULL,
    image_data bytea NOT NULL,
    model varchar(100) NOT NULL,
    prompt_version varchar(80) NOT NULL,
    raw_scan jsonb NOT NULL,
    selected_index integer,
    reviewed_product jsonb,
    CONSTRAINT scan_records_review_pair CHECK (
        (selected_index IS NULL AND reviewed_product IS NULL)
        OR (selected_index IS NOT NULL AND reviewed_product IS NOT NULL)
    )
);

CREATE INDEX scan_records_created_at_idx ON scan_records (created_at DESC);
