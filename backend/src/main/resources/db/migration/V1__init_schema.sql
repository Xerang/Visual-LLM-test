-- BOZOR 서비스 스키마 v1
-- 대상: PostgreSQL 16+ (UTF-8 로케일 DB 필수, 아래 검사 참고)
-- 설계 근거: docs/02-erd.md, 현지 조사: docs/01-tajikistan-research.md
-- 이미 적용된 이 파일은 고치지 않는다. 스키마 변경은 새 버전 파일(V3__...)로 추가한다.
--
-- 공통 규칙
--   * PK는 bigint identity, 시각은 모두 timestamptz (현지 Asia/Dushanbe, UTC+5)
--   * 금액은 numeric(12,2) + currency(기본 TJS, 1 somoni = 100 diram)
--   * 상태값은 varchar + CHECK (Java enum 이름과 동일하게 대문자)
--   * locale: tg(타직어, 키릴), ru(러시아어), en, ko. DB에는 기본값을 두지 않고 애플리케이션
--     설정(app.default-locale)에서 채운다. 현재는 ko(임시), 실증 전 tg/ru로 바꾼다.
--   * updated_at 갱신은 애플리케이션(JPA)에서 처리한다.
--   * 임시 설정과 실증 전 변경 목록: docs/00-temporary-decisions.md

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- DB 로케일(LC_CTYPE)이 C이면 pg_trgm이 키릴 문자를 글자로 인식하지 못해 상품 검색이
-- 항상 0건이 된다. 조용히 틀리지 않도록 마이그레이션 단계에서 바로 실패시킨다.
DO $$
BEGIN
    IF show_trgm('Курага') = '{}'::text[] THEN
        RAISE EXCEPTION 'DB LC_CTYPE(%)가 키릴 문자를 지원하지 않습니다. UTF-8 로케일로 DB를 다시 만드세요.',
            (SELECT datctype FROM pg_database WHERE datname = current_database());
    END IF;
END $$;

-- 1. 사용자 ------------------------------------------------------------------
-- 판매자/구매자를 따로 나누지 않는다. 상점(stores)을 가진 사용자가 판매자다.
CREATE TABLE users (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number         varchar(16)  NOT NULL UNIQUE
                         CHECK (phone_number ~ '^\+[1-9][0-9]{7,14}$'),
    -- 목(mock) 로그인 단계에서는 NULL. 실제 인증(비밀번호/OTP)을 정할 때 채우거나 대체한다.
    password_hash        varchar(100),
    display_name         varchar(50)  NOT NULL,
    locale               varchar(2)   NOT NULL CHECK (locale IN ('tg', 'ru', 'en', 'ko')),
    role                 varchar(10)  NOT NULL DEFAULT 'USER'
                         CHECK (role IN ('USER', 'ADMIN')),
    -- 개인정보보호법(No.1537, 2018): 해외(Gemini·S3) 전송은 동의를 근거로 한다.
    privacy_consented_at timestamptz  NOT NULL,
    created_at           timestamptz  NOT NULL DEFAULT now(),
    updated_at           timestamptz  NOT NULL DEFAULT now()
);

-- 2. 이미지 ------------------------------------------------------------------
-- 원본 바이트는 DB가 아니라 오브젝트 스토리지(S3/로컬 디스크)에 둔다.
-- 저장 전에 EXIF(촬영 위치 등)를 제거한 정규화 이미지만 보관한다.
CREATE TABLE images (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uploader_id       bigint       NOT NULL REFERENCES users (id),
    storage_key       varchar(255) NOT NULL UNIQUE,
    thumbnail_key     varchar(255),
    mime_type         varchar(32)  NOT NULL
                      CHECK (mime_type IN ('image/jpeg', 'image/png', 'image/webp')),
    width             integer      NOT NULL CHECK (width > 0),
    height            integer      NOT NULL CHECK (height > 0),
    byte_size         integer      NOT NULL CHECK (byte_size > 0),
    sha256            char(64)     NOT NULL,
    original_filename varchar(255),
    created_at        timestamptz  NOT NULL DEFAULT now()
);
-- 같은 판매자가 같은 사진을 다시 올렸는지(SNS 일괄 등록 중복) 빠르게 찾는다.
CREATE INDEX images_uploader_sha256_idx ON images (uploader_id, sha256);

-- 3. 시장 --------------------------------------------------------------------
-- 두샨베 Mehrgon(식품·수공예), Korvon(의류·생활용품) 등. 지도/길찾기는 범위 밖.
CREATE TABLE markets (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    city varchar(50)  NOT NULL,
    UNIQUE (city, name)
);

-- 4. 상점 --------------------------------------------------------------------
CREATE TABLE stores (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id          bigint       NOT NULL REFERENCES users (id),
    slug              varchar(60)  NOT NULL UNIQUE
                      CHECK (slug ~ '^[a-z0-9][a-z0-9-]{1,58}[a-z0-9]$'),
    name              varchar(80)  NOT NULL,
    description       text,
    -- 2차 회의: 업종별 자동 레이아웃 대신 템플릿 3종 + 커스터마이즈 (임시 정의: 02-erd.md)
    -- GRID=진열대(식품·소품), LIST=가격표(품목 많음·저속 회선), SHOWCASE=공방(수공예)
    template          varchar(10)  NOT NULL DEFAULT 'GRID'
                      CHECK (template IN ('GRID', 'LIST', 'SHOWCASE')),
    theme_color       char(7)      CHECK (theme_color ~ '^#[0-9A-Fa-f]{6}$'),
    logo_image_id     bigint       REFERENCES images (id),
    banner_image_id   bigint       REFERENCES images (id),
    market_id         bigint       REFERENCES markets (id),
    location_detail   varchar(100),            -- 시장 안 위치: 줄·칸 번호 등
    address_text      varchar(255),
    landmark          varchar(255),            -- 현지 주소는 랜드마크(ориентир) 병기가 일반적
    contact_phone     varchar(16)  CHECK (contact_phone ~ '^\+[1-9][0-9]{7,14}$'),
    whatsapp_phone    varchar(16)  CHECK (whatsapp_phone ~ '^\+[1-9][0-9]{7,14}$'),
    instagram_handle  varchar(30),
    telegram_username varchar(32),
    status            varchar(10)  NOT NULL DEFAULT 'DRAFT'
                      CHECK (status IN ('DRAFT', 'ACTIVE', 'HIDDEN')),
    created_at        timestamptz  NOT NULL DEFAULT now(),
    updated_at        timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX stores_owner_idx ON stores (owner_id);
CREATE INDEX stores_market_idx ON stores (market_id);

-- 5. 카테고리 ----------------------------------------------------------------
-- 카테고리 목록의 단일 출처. AI 프롬프트의 허용 값도 이 테이블에서 만든다
-- (PoC에서 Python Literal과 Java Set에 중복 정의돼 있던 문제 해소).
-- 규칙: 최대 2단계(대분류.소분류). 상품·AI 후보는 말단(leaf) 카테고리만 가리킨다
-- (자식이 없는 대분류도 말단). 말단 여부와 단계 제한은 애플리케이션에서 검사한다.
CREATE TABLE categories (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id    bigint      REFERENCES categories (id),
    code         varchar(40) NOT NULL UNIQUE CHECK (code ~ '^[a-z_]+(\.[a-z_]+)?$'),
    -- 상품 등록 시 제안할 판매 단위 (말린 과일 → KG, 원단 → METER)
    default_unit varchar(6)  CHECK (default_unit IN ('PIECE', 'KG', 'LITER', 'METER', 'SET')),
    sort_order   integer     NOT NULL DEFAULT 0,
    is_active    boolean     NOT NULL DEFAULT true
);

CREATE TABLE category_translations (
    category_id bigint      NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    locale      varchar(2)  NOT NULL CHECK (locale IN ('tg', 'ru', 'en', 'ko')),
    name        varchar(60) NOT NULL,
    PRIMARY KEY (category_id, locale)
);

-- 6. AI 스캔 작업 (비동기 Job) ----------------------------------------------
-- 2차 회의 결정: AI 응답(5~30초+)은 동기 대기 대신 Job으로 처리한다.
-- 워커는 status = 'QUEUED' AND available_at <= now() 인 Job을 FOR UPDATE SKIP LOCKED 로 가져간다.
-- 재시도 가능한 실패(429·503·504)는 QUEUED로 되돌리고 available_at을 미뤄서 연속 호출을 막는다.
CREATE TABLE scan_jobs (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id       bigint       NOT NULL REFERENCES stores (id),
    requested_by   bigint       NOT NULL REFERENCES users (id),
    source_type    varchar(12)  NOT NULL
                   CHECK (source_type IN ('CAMERA', 'UPLOAD', 'SNS_IMPORT')),
    caption_text   text,                       -- SNS 게시물 캡션(가격 등 텍스트 정보)
    output_locale  varchar(2)   NOT NULL CHECK (output_locale IN ('tg', 'ru', 'en', 'ko')),
    status         varchar(10)  NOT NULL DEFAULT 'QUEUED'
                   CHECK (status IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    attempt_count  smallint     NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    available_at   timestamptz  NOT NULL DEFAULT now(),  -- 이 시각 이후에 워커가 가져간다
    model          varchar(100),
    prompt_version varchar(40),
    raw_result     jsonb,                      -- AI 원본 응답. 이후 절대 수정하지 않는다.
    error_code     varchar(40),
    error_message  varchar(500),
    elapsed_ms     integer      CHECK (elapsed_ms >= 0),
    created_at     timestamptz  NOT NULL DEFAULT now(),
    started_at     timestamptz,
    finished_at    timestamptz,
    reviewed_at    timestamptz,                -- 판매자 검수 완료 시각
    CONSTRAINT scan_jobs_succeeded_has_result CHECK (
        status <> 'SUCCEEDED'
        OR (raw_result IS NOT NULL AND model IS NOT NULL AND prompt_version IS NOT NULL)),
    CONSTRAINT scan_jobs_failed_has_error CHECK (status <> 'FAILED' OR error_code IS NOT NULL)
);
CREATE INDEX scan_jobs_queue_idx ON scan_jobs (available_at) WHERE status = 'QUEUED';
CREATE INDEX scan_jobs_store_idx ON scan_jobs (store_id, created_at DESC);

-- 한 Job에 사진 1~3장(인스타 캐러셀 포함). 개수 제한은 애플리케이션에서 검사.
CREATE TABLE scan_job_images (
    scan_job_id bigint   NOT NULL REFERENCES scan_jobs (id) ON DELETE CASCADE,
    image_id    bigint   NOT NULL REFERENCES images (id),
    sort_order  smallint NOT NULL DEFAULT 0,
    PRIMARY KEY (scan_job_id, image_id)
);

-- 7. 스캔 후보 ---------------------------------------------------------------
-- AI가 제안한 후보(origin=AI)와 AI가 놓쳐 판매자가 추가한 상품(origin=SELLER)을
-- 같은 테이블에 둬서 정확도·정밀도·재현율을 SQL로 바로 계산한다.
CREATE TABLE scan_candidates (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_job_id     bigint        NOT NULL REFERENCES scan_jobs (id) ON DELETE CASCADE,
    candidate_index smallint      NOT NULL CHECK (candidate_index >= 0),
    origin          varchar(6)    NOT NULL CHECK (origin IN ('AI', 'SELLER')),
    name            varchar(120)  NOT NULL,
    description     text,
    category_id     bigint        NOT NULL REFERENCES categories (id),
    visible_text    jsonb         NOT NULL DEFAULT '[]'
                    CHECK (jsonb_typeof(visible_text) = 'array'),
    review_notes    jsonb         NOT NULL DEFAULT '[]'
                    CHECK (jsonb_typeof(review_notes) = 'array'),
    suggested_price numeric(12,2) CHECK (suggested_price >= 0),  -- 캡션에 적힌 가격만
    decision        varchar(10)   NOT NULL DEFAULT 'PENDING'
                    CHECK (decision IN ('PENDING', 'ACCEPTED', 'REJECTED')),
    created_at      timestamptz   NOT NULL DEFAULT now(),
    UNIQUE (scan_job_id, candidate_index),
    CONSTRAINT scan_candidates_seller_is_accepted CHECK (origin <> 'SELLER' OR decision = 'ACCEPTED')
);

-- 8. 상품 --------------------------------------------------------------------
CREATE TABLE products (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id            bigint        NOT NULL REFERENCES stores (id),
    category_id         bigint        NOT NULL REFERENCES categories (id),
    source_candidate_id bigint        UNIQUE REFERENCES scan_candidates (id),  -- 직접 등록이면 NULL
    status              varchar(10)   NOT NULL DEFAULT 'DRAFT'
                        CHECK (status IN ('DRAFT', 'PUBLISHED', 'HIDDEN', 'ARCHIVED')),
    price               numeric(12,2) CHECK (price >= 0),
    currency            char(3)       NOT NULL DEFAULT 'TJS',
    -- 바자르는 흥정이 관행: NEGOTIABLE은 "기준가 + 흥정 가능". 가격 자체는 필수로 받아
    -- "가격은 DM 문의" 문제를 해결한다.
    price_type          varchar(10)   NOT NULL DEFAULT 'FIXED'
                        CHECK (price_type IN ('FIXED', 'NEGOTIABLE')),
    -- 말린 과일·향신료·견과류처럼 무게 단위 판매 대응
    unit                varchar(6)    NOT NULL DEFAULT 'PIECE'
                        CHECK (unit IN ('PIECE', 'KG', 'LITER', 'METER', 'SET')),
    stock_quantity      numeric(10,3) CHECK (stock_quantity >= 0),          -- NULL = 재고 관리 안 함
    published_at        timestamptz,
    created_at          timestamptz   NOT NULL DEFAULT now(),
    updated_at          timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT products_published_needs_price CHECK (
        status <> 'PUBLISHED' OR (price IS NOT NULL AND published_at IS NOT NULL))
);
CREATE INDEX products_store_status_idx ON products (store_id, status);
CREATE INDEX products_category_published_idx ON products (category_id) WHERE status = 'PUBLISHED';

-- 상품명·설명은 언어별로 저장. 검색은 pg_trgm(키릴 문자 지원)으로 처리.
CREATE TABLE product_translations (
    product_id         bigint       NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    locale             varchar(2)   NOT NULL CHECK (locale IN ('tg', 'ru', 'en', 'ko')),
    name               varchar(120) NOT NULL,
    description        text,
    is_auto_translated boolean      NOT NULL DEFAULT false,  -- 판매자가 확인하지 않은 기계 번역
    updated_at         timestamptz  NOT NULL DEFAULT now(),
    PRIMARY KEY (product_id, locale)
);
CREATE INDEX product_translations_name_trgm_idx
    ON product_translations USING gin (name gin_trgm_ops);

-- 진열대 사진 한 장이 여러 상품의 이미지가 될 수 있다(N:M).
CREATE TABLE product_images (
    product_id bigint   NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    image_id   bigint   NOT NULL REFERENCES images (id),
    sort_order smallint NOT NULL DEFAULT 0,               -- 0 = 대표 이미지
    PRIMARY KEY (product_id, image_id)
);

-- 9. 주문 (실결제·배송추적 제외, 상태 관리까지) -------------------------------
-- 한 주문 = 한 상점. 현금(대면·착불)과 지갑/카드 송금(판매자가 수동 확인)만 기록.
CREATE TABLE orders (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number     varchar(20)   NOT NULL UNIQUE,
    buyer_id         bigint        NOT NULL REFERENCES users (id),
    store_id         bigint        NOT NULL REFERENCES stores (id),
    status           varchar(10)   NOT NULL DEFAULT 'REQUESTED'
                     CHECK (status IN ('REQUESTED', 'CONFIRMED', 'READY', 'COMPLETED',
                                       'REJECTED', 'CANCELLED')),
    fulfillment_type varchar(10)   NOT NULL CHECK (fulfillment_type IN ('PICKUP', 'DELIVERY')),
    payment_method   varchar(10)   NOT NULL DEFAULT 'CASH'
                     CHECK (payment_method IN ('CASH', 'TRANSFER')),
    contact_phone    varchar(16)   NOT NULL CHECK (contact_phone ~ '^\+[1-9][0-9]{7,14}$'),
    delivery_address varchar(255),
    landmark         varchar(255),
    buyer_note       varchar(500),
    total_amount     numeric(12,2) NOT NULL CHECK (total_amount >= 0),  -- 흥정 상품 포함 시 예상 금액
    currency         char(3)       NOT NULL DEFAULT 'TJS',
    -- 재고는 자동 차감하지 않는다. 판매자가 주문 접수 때 "재고에서 빼기"를 고른 경우만 true.
    -- 접수 후 취소되면 이 값을 보고 재고를 되돌린다.
    stock_deducted   boolean       NOT NULL DEFAULT false,
    created_at       timestamptz   NOT NULL DEFAULT now(),
    updated_at       timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT orders_delivery_needs_address CHECK (
        fulfillment_type <> 'DELIVERY' OR delivery_address IS NOT NULL)
);
CREATE INDEX orders_buyer_idx ON orders (buyer_id, created_at DESC);
CREATE INDEX orders_store_idx ON orders (store_id, status, created_at DESC);

-- 주문 시점의 상품명·가격·단위를 스냅샷으로 보관(이후 상품 수정과 무관).
CREATE TABLE order_items (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     bigint        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id   bigint        NOT NULL REFERENCES products (id),
    product_name varchar(120)  NOT NULL,
    unit_price   numeric(12,2) NOT NULL CHECK (unit_price >= 0),
    price_type   varchar(10)   NOT NULL CHECK (price_type IN ('FIXED', 'NEGOTIABLE')),
    unit         varchar(6)    NOT NULL CHECK (unit IN ('PIECE', 'KG', 'LITER', 'METER', 'SET')),
    quantity     numeric(10,3) NOT NULL CHECK (quantity > 0),
    line_total   numeric(12,2) NOT NULL CHECK (line_total >= 0),
    UNIQUE (order_id, product_id)
);
