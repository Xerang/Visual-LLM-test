-- 근거: 2차 회의 추가 기능 "기존 SNS 이미지 일괄 등록"(시연 시점에 상품이 비어 있는 문제 대응),
--       검증 지표 "상점 온보딩 소요시간: 이미지 20장 기준 5분 이내". 설계: docs/02-erd.md
--
-- 온보딩 소요시간 = created_at(사진을 고르자마자 만든다, 업로드 전) → 묶음의 마지막 검수 완료 시각
-- 시각은 모두 서버 시각이다(휴대폰 시계는 믿지 않는다).
CREATE TABLE import_batches (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id     bigint      NOT NULL REFERENCES stores (id),
    requested_by bigint      NOT NULL REFERENCES users (id),
    created_at   timestamptz NOT NULL DEFAULT now(),
    submitted_at timestamptz,          -- 업로드·캡션 입력을 마치고 AI 분석을 요청한 시각(한 번만)
    CONSTRAINT import_batches_submitted_after_created CHECK (submitted_at IS NULL OR submitted_at >= created_at)
);
CREATE INDEX import_batches_store_idx ON import_batches (store_id, created_at DESC);

-- 묶음으로 만든 스캔 작업. 단건 스캔은 NULL.
ALTER TABLE scan_jobs ADD COLUMN import_batch_id bigint REFERENCES import_batches (id);
CREATE INDEX scan_jobs_import_batch_idx ON scan_jobs (import_batch_id) WHERE import_batch_id IS NOT NULL;
